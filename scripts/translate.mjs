const argv = process.argv.slice(2);
const flag = (n) => argv.includes(`--${n}`);
const val = (n) => { const i = argv.indexOf(`--${n}`); return i < 0 ? undefined : argv[i + 1]; };

if (import.meta.url === `file://${process.argv[1]}`) {
  if (flag('scan')) scan();
  else if (flag('assist')) await assist({ limit: Number(val('limit')) || undefined, section: val('section'), redraft: flag('redraft') });
  else if (flag('emit')) { scan({ quiet: true }); emit(); }
  else if (flag('review')) {
    const mem = loadMem();
    const ids = argv.filter((a) => !a.startsWith('--'));
    const { units } = scan({ quiet: true });
    let n = 0;
    for (const id of ids) if (mem.units[id]?.zh) { mem.units[id].status = 'reviewed'; n++; }
    saveMem(mem, units.map((u) => u.id));
    console.log(`\n  ${n} unit(s) marked reviewed\n`);
  } else if (flag('check')) {
    const v = validate();
    if (v.findings.length) {
      console.error(`\n  translation memory: ${v.findings.length} finding(s)`);
      for (const f of v.findings.slice(0, 20)) console.error(`    ✗ ${f.id} — ${f.what}: ${f.detail}`);
      process.exit(1);
    }
    console.log(`  translation memory: ${v.units.length} units, ${v.owed.length} owed, no findings`);
  } else status();
}

