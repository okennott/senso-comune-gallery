/** docs/report/translations/STATUS.md — the same numbers --status prints, as a
 *  file a reader can open without running anything. Written by --emit as well,
 *  so the record and the composed document are never a build apart. */
function writeStatus(v) {
  const byKind = {};
  for (const u of v.units) {
    const s = v.mem.units[u.id];
    const k = byKind[u.kind] ?? (byKind[u.kind] = { total: 0, reviewed: 0, draft: 0, owed: 0, stale: 0 });
    k.total++;
    if (!s?.zh) k.owed++;
    else if (s.status === 'stale') k.stale++;
    else k[s.status === 'reviewed' ? 'reviewed' : 'draft']++;
  }
  const pct = (n, d) => (d ? `${Math.round((n / d) * 100)}%` : '—');
  const rows = Object.entries(byKind).sort((a, b) => b[1].total - a[1].total);

  const lines = [];
  lines.push('# Chinese report — translation status', '',
    `Generated by \`node scripts/translate.mjs --status\` on ${today()}.`, '',
    '| Unit kind | Total | Reviewed | Draft | Stale | Owed |',
    '|:----------|------:|---------:|------:|------:|-----:|');
  for (const [kind, k] of rows)
    lines.push(`| ${kind} | ${k.total} | ${k.reviewed} | ${k.draft} | ${k.stale} | ${k.owed} |`);
  const T = v.units.length;
  lines.push(`| **all** | **${T}** | **${v.reviewed.length}** (${pct(v.reviewed.length, T)}) | **${v.draft.length}** | **${v.units.filter((u) => v.mem.units[u.id]?.status === 'stale').length}** | **${v.owed.length}** |`, '');

  if (v.findings.length) {
    lines.push(`## ${v.findings.length} finding(s)`, '');
    for (const f of v.findings.slice(0, 200)) lines.push(`- \`${f.id}\` — ${f.what}: ${f.detail}`);
    if (v.findings.length > 200) lines.push(`- … and ${v.findings.length - 200} more`);
    lines.push('');
  } else lines.push('No findings: every translation in the memory carries its code, its', 'cross-references and the project\'s own vocabulary.', '');

  mkdirSync(MEMDIR, { recursive: true });
  const text = lines.join('\n');
  if (!existsSync(STATUS) || readFileSync(STATUS, 'utf8') !== text) writeFileSync(STATUS, text);
  return { rows, T, pct };
}

function status() {
  const v = validate();
  const { rows, T, pct } = writeStatus(v);

  console.log(`\n  ${T} units — ${v.reviewed.length} reviewed (${pct(v.reviewed.length, T)}), ${v.draft.length} draft, ${v.owed.length} owed`);
  for (const [kind, k] of rows)
    console.log(`    ${kind.padEnd(9)} ${String(k.total).padStart(5)}  reviewed ${String(k.reviewed).padStart(4)}  draft ${String(k.draft).padStart(4)}  owed ${String(k.owed).padStart(4)}`);
  if (v.findings.length) {
    console.log(`\n  ${v.findings.length} finding(s); first ten:`);
    for (const f of v.findings.slice(0, 10)) console.log(`    ✗ ${f.id} — ${f.what}: ${f.detail}`);
  }
  console.log(`\n  written: ${STATUS.replace(ROOT + '/', '')}\n`);
  return v;
}

