/**
 * Content-aware English → Chinese translation for the technical report.
 *
 *   node scripts/translate.mjs --status            what is translated, what is owed
 *   node scripts/translate.mjs --scan              re-segment the source into the memory
 *   node scripts/translate.mjs --assist [--limit N] [--section sec-x]
 *                                                 draft the units still owed
 *   node scripts/translate.mjs --review <id>...    mark units reviewed
 *   node scripts/translate.mjs --emit              write the Chinese .qmd
 *   node scripts/translate.mjs --check             validate the memory
 *
 * WHAT "CONTENT-AWARE" MEANS HERE
 * The report is 3,000 lines of prose with the machinery of a typeset document
 * running through it: inline LaTeX, `\index` entries, `@sec-` cross-references,
 * pipe tables, figure captions with attribute blocks, footnote references, CSS
 * variable names, hex values and file paths. Handing that to any translator as
 * plain text returns a document that no longer compiles and whose
 * cross-references point nowhere.
 *
 * So the source is segmented into units by KIND, and inside a unit every span
 * that is not prose is replaced by a sentinel before translation and restored
 * after. A translation that lost a sentinel is rejected rather than written.
 * The project's own vocabulary is applied on top of that, from the one corpus
 * in scripts/corpus.mjs — so the report says 作品 and 购买方式 because that is
 * what the site says, not because a translator happened to choose them.
 *
 * WHY THE BUILD NEVER TRANSLATES
 * Translation happens here, when a person runs it, and lands in a memory file
 * that is reviewed and committed. docs/report/build.sh only ever COMPOSES: it
 * reads the memory and writes the .qmd. Two reasons. A document that quotes
 * SAMR Order 37 verbatim must not have its statutory text regenerated by a
 * model on every build; and a PDF that needs the network to reproduce is not
 * reproducible. Each unit is keyed by a hash of its English, so editing an
 * English sentence marks its Chinese stale instead of leaving it silently
 * attached to text it no longer translates.
 *
 * WHAT AN UNTRANSLATED UNIT DOES
 * It falls back to English, and says so: `\zhmark{}` in the margin of the
 * passage, a count on the title page, and a line per unit in --status. The
 * same discipline as the site's NEEDS-INPUT marks — a gap a reader cannot see
 * is a gap nobody closes.
 */

